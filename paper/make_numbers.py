"""Write paper/numbers.tex: every number in the paper as a macro read from results/."""
import glob
import json
import os

import numpy as np
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
R = os.path.join(ROOT, "results")
circ = json.load(open(os.path.join(R, "circuit_stats.json")))
runs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(R, "runs", "seed*", "summary.json")))]
cfg = json.load(open(os.path.join(R, "runs", "seed0", "config.json")))
ref = pd.read_csv(os.path.join(R, "reference_agents.csv")).set_index("agent")
diag = pd.read_csv(os.path.join(R, "diagnose.csv")).set_index("variant")
les = pd.read_csv(os.path.join(R, "lesion.csv"))


def f(x, d=1):
    return f"{x:.{d}f}"


good = [r for r in runs if r["test_match_win_rate"] >= 0.5]
bad = [r for r in runs if r["test_match_win_rate"] < 0.5]
mid = les[les.condition == "all intermediates (hDelta)"]
m = {
    "Neurons": circ["neurons"], "Inputs": circ["inputs"], "NPFNa": circ["input_types"]["PFNa"],
    "NPFNd": circ["input_types"]["PFNd"], "NPFNv": circ["input_types"]["PFNv"],
    "Intermediates": circ["intermediates"], "NhDeltaA": circ["intermediate_types"].get("hDeltaA", 0),
    "Outputs": circ["outputs"], "Edges": circ["edges"], "EdgesInMid": circ["edges_input_to_intermediate"],
    "EdgesMidOut": circ["edges_intermediate_to_output"], "EdgesWithinInputs": circ["edges_within_inputs"],
    "EdgesDirect": circ["edges_input_to_output"], "NParams": runs[0]["n_params"], "NSeeds": len(runs),
    "TestGames": cfg["test_games"], "BudgetFrames": f"{cfg['budget_frames']:,}".replace(",", "{,}"),
    "NGood": len(good), "NBad": len(bad),
    "GoodWinPct": f(100 * np.mean([r["test_match_win_rate"] for r in good]), 0),
    "GoodAgainstMin": f(min(r["test_points_against"] for r in good), 2),
    "GoodAgainstMax": f(max(r["test_points_against"] for r in good), 2),
    "GoodReturnMin": f(100 * min(r["test_return_rate"] for r in good), 1),
    "BadFor": f(bad[0]["test_points_for"], 2) if bad else "--", "BadAgainst": f(bad[0]["test_points_against"], 2) if bad else "--",
    "BadWinPct": f(100 * bad[0]["test_match_win_rate"], 0) if bad else "--", "BadSeed": bad[0]["seed"] if bad else "--",
    "TrainTimeMean": f(np.mean([r["train_time_s"] for r in runs]), 0),
    "RuleFor": f(ref.loc["track_ball_rule", "points_for"], 2), "RuleAgainst": f(ref.loc["track_ball_rule", "points_against"], 2),
    "RuleWinPct": f(100 * ref.loc["track_ball_rule", "match_win_rate"], 0),
    "StillFor": f(ref.loc["paddle_still", "points_for"], 2), "StillAgainst": f(ref.loc["paddle_still", "points_against"], 2),
    "RandFor": f(ref.loc["random_moves", "points_for"], 2), "RandAgainst": f(ref.loc["random_moves", "points_against"], 2),
    "DiagBaseFor": f(diag.loc["base", "val_points_for"], 2), "DiagBaseAgainst": f(diag.loc["base", "val_points_against"], 2),
    "DiagBestFor": f(diag.loc["per-neuron readout, k_in 16", "val_points_for"], 2),
    "DiagBestAgainst": f(diag.loc["per-neuron readout, k_in 16", "val_points_against"], 2),
    "MidLesForMax": f(mid.points_for.max(), 1),
}
with open(os.path.join(ROOT, "paper", "numbers.tex"), "w") as fh:
    fh.write("% generated by paper/make_numbers.py from results/ -- do not edit\n")
    for k, v in m.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    piv_for = les.pivot(index="condition", columns="seed", values="points_for")
    piv_ag = les.pivot(index="condition", columns="seed", values="points_against")
    order = list(dict.fromkeys(les.condition))
    rows = " ".join(f"{c.replace('hDelta', '$h\\Delta$')} & " + " & ".join(f"{piv_for.loc[c, s]:.1f}--{piv_ag.loc[c, s]:.1f}" for s in piv_for.columns) + r" \\" for c in order)
    fh.write("\\newcommand{\\LesionRows}{" + rows + "}\n")
    rows2 = " ".join(f"{d.Index.replace('_', chr(92) + '_')} & {d.n_params} & {d.val_points_for:.2f}--{d.val_points_against:.2f} & {d.val_hits:.1f} \\\\"
                     for d in pd.read_csv(os.path.join(R, "diagnose.csv")).rename(columns={"variant": "Index"}).itertuples(index=False))
    fh.write("\\newcommand{\\DiagRows}{" + rows2 + "}\n")
    rows3 = " ".join(f"{r['seed']} & {r['test_points_for']:.2f}--{r['test_points_against']:.2f} & {100 * r['test_match_win_rate']:.0f}\\% & {r['test_hits']:.1f} & {100 * r['test_return_rate']:.1f}\\% & {r['train_time_s']:.0f} \\\\" for r in runs)
    fh.write("\\newcommand{\\SeedRows}{" + rows3 + "}\n")
print(open(os.path.join(ROOT, "paper", "numbers.tex")).read())
